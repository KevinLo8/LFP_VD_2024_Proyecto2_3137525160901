class Configuracion {

    getFondo() {
        return this.fondo;
    }

    setFondo(fondo) {
        this.fondo = fondo;
    }   

    getFuente() {
        return this.fuente;
    }

    setFuente(fuente) {
        this.fuente = fuente;
    }

    getForma() {
        return this.forma;
    }

    setForma(forma) {
        this.forma = forma;
    }

    getTipoFuente() {
        return this.tipoFuente;
    }

    setTipoFuente(tipoFuente) {
        this.tipoFuente = tipoFuente;
    }
    
}

module.exports = Configuracion;